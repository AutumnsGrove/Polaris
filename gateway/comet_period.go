// comet_period.go holds Comet's period arithmetic — what "YYYY-MM" a
// retrospective covers, and its [start, end) bounds in the operator's own
// zone. Kept apart from the scheduler/generation code so the boundary math
// (the part most likely to be subtly wrong around DST and month lengths)
// has one home and is testable on its own.
package gateway

import (
	"fmt"
	"time"

	"polaris/tz"
)

// cometMonthOf returns the "YYYY-MM" of the calendar month CONTAINING t, in
// the active zone.
func cometMonthOf(t time.Time) string {
	return t.Format("2006-01")
}

// cometPeriodOf returns the "YYYY-MM" period of the most recent *complete*
// calendar month at time t — the month a retrospective generated "now"
// describes. Comet never generates for the month it's currently in: the
// plan doc's "hard dependency on that period's Trails being complete" means
// a partial month would be a misleading edition. This is deliberately not
// cometMonthOf: passing it the month containing a message gives the month
// BEFORE it, which is what you want for "the retrospective due now", not
// for "which month does this activity belong to".
func cometPeriodOf(t time.Time) string {
	y, m, _ := t.Date()
	m--
	if m < time.January {
		m = time.December
		y--
	}
	return fmt.Sprintf("%04d-%02d", y, int(m))
}

// cometAddMonths shifts a "YYYY-MM" period by n months, staying in the
// active zone. ok is false for a malformed period.
func cometAddMonths(period string, n int) (string, bool) {
	start, err := time.ParseInLocation("2006-01", period, tz.Location())
	if err != nil {
		return "", false
	}
	return start.AddDate(0, n, 0).Format("2006-01"), true
}

// cometPeriodBounds parses a "YYYY-MM" period into its [start, end) window
// in the active zone. ok is false for a malformed period string (a
// defensive check — every period is either generated by cometPeriodOf or
// validated by the API before it reaches here).
func cometPeriodBounds(period string) (start, end time.Time, ok bool) {
	start, err := time.ParseInLocation("2006-01", period, tz.Location())
	if err != nil {
		return time.Time{}, time.Time{}, false
	}
	return start, start.AddDate(0, 1, 0), true
}

// cometPeriodDB returns a period's [start, end) bounds formatted the way
// every created_at/updated_at column stores them (UTC, "YYYY-MM-DD
// HH:MM:SS") — the form all the Comet aggregation queries compare
// against. ok is false for a malformed period.
func cometPeriodDB(period string) (startStr, endStr string, ok bool) {
	start, end, ok := cometPeriodBounds(period)
	if !ok {
		return "", "", false
	}
	return start.UTC().Format("2006-01-02 15:04:05"), end.UTC().Format("2006-01-02 15:04:05"), true
}

// cometPeriodLabel is the masthead's human label, e.g. "September 2026".
func cometPeriodLabel(period string) string {
	start, _, ok := cometPeriodBounds(period)
	if !ok {
		return period
	}
	return start.Format("January 2006")
}

// cometBaselineStart returns the start of the trailing baseline window a
// period's spiked/faded pass compares against — baselineDays before the
// period's own start, in UTC DB format. The operator's call (see the plan
// doc's "Spiked/faded" section) was 60-90 days; 90 is used so something
// dug into in July and quiet by September still shows the trailing
// presence that makes it eligible to have faded.
func cometBaselineStart(period string, baselineDays int) (string, bool) {
	start, _, ok := cometPeriodBounds(period)
	if !ok {
		return "", false
	}
	return start.AddDate(0, 0, -baselineDays).UTC().Format("2006-01-02 15:04:05"), true
}
